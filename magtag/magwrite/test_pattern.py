def draw_text(epd, text, x, y, scale=1):
    for character in text:
        glyph = GLYPHS[character]
        for gy, row in enumerate(glyph):
            for gx, pixel in enumerate(row):
                if pixel == "1":
                    landscape_rect(
                        epd, x + gx * scale, y + gy * scale, scale, scale, 1
                    )
        x += 4 * scale
